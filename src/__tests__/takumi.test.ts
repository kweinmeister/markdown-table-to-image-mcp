import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { parseMarkdownTable } from "../parser.js";
import { renderTableToImage, renderTableToPng } from "../takumi.js";

function parsePngDimensions(png: Buffer): { width: number; height: number } {
  // PNG IHDR chunk starts at byte 16: 4 bytes width, 4 bytes height (big-endian)
  const width = png.readUInt32BE(16);
  const height = png.readUInt32BE(20);
  return { width, height };
}

describe("Takumi Render Engine", () => {
  it("should compile a table to a valid, non-empty PNG buffer", async () => {
    const table = parseMarkdownTable(`
| Component | Speed | Size |
| :--- | :---: | ---: |
| FastMCP | Instant | Tiny |
| Takumi | Rapid | Small |
| Biome | Blazing | Micro |
    `);

    const pngBuffer = await renderTableToPng({
      table,
      title: "Benchmark Results",
      theme: "glassmorphism",
      aspectRatio: "auto",
      scale: 1.5,
    });

    expect(pngBuffer).toBeDefined();
    expect(pngBuffer.length).toBeGreaterThan(0);
    // PNG files always start with magic bytes 0x89 0x50 0x4E 0x47
    expect(pngBuffer[0]).toBe(0x89);
    expect(pngBuffer[1]).toBe(0x50);
    expect(pngBuffer[2]).toBe(0x4e);
    expect(pngBuffer[3]).toBe(0x47);
  });

  it("should render under all themes including editorial", async () => {
    const table = parseMarkdownTable(`
| Theme | Color |
| --- | --- |
| Light | White |
| Dark | Black |
    `);

    const themes = [
      "glassmorphism",
      "slate-dark",
      "minimalist-light",
      "emerald-glow",
      "synthwave",
      "editorial",
    ] as const;

    for (const theme of themes) {
      const buffer = await renderTableToImage({
        table,
        title: `Test Theme: ${theme}`,
        subtitle: "Theme rendering test suite",
        footer: "Generated by markdown-table-to-image-mcp",
        theme,
        aspectRatio: "16:9",
        customWidth: 600,
      });
      expect(buffer).toBeDefined();
      expect(buffer.length).toBeGreaterThan(0);
    }
  });

  it("should scale output pixel dimensions by the scale factor", async () => {
    const table = parseMarkdownTable(`
| A | B |
| --- | --- |
| 1 | 2 |
    `);

    const png1x = await renderTableToPng({
      table,
      aspectRatio: "auto",
      customWidth: 400,
      scale: 1,
    });
    const png2x = await renderTableToPng({
      table,
      aspectRatio: "auto",
      customWidth: 400,
      scale: 2,
    });

    const dim1x = parsePngDimensions(png1x);
    const dim2x = parsePngDimensions(png2x);

    expect(dim2x.width).toBe(dim1x.width * 2);
    expect(dim2x.height).toBe(dim1x.height * 2);
  });

  it("should produce correct pixel dimensions for each aspect ratio", async () => {
    const table = parseMarkdownTable(`
| A | B |
| --- | --- |
| 1 | 2 |
    `);

    const auto = await renderTableToPng({ table, aspectRatio: "auto", customWidth: 800, scale: 1 });
    const wide = await renderTableToPng({ table, aspectRatio: "16:9", customWidth: 800, scale: 1 });
    const square = await renderTableToPng({
      table,
      aspectRatio: "1:1",
      customWidth: 800,
      scale: 1,
    });
    const tall = await renderTableToPng({ table, aspectRatio: "9:16", customWidth: 800, scale: 1 });

    const autoDim = parsePngDimensions(auto);
    const wideDim = parsePngDimensions(wide);
    const squareDim = parsePngDimensions(square);
    const tallDim = parsePngDimensions(tall);

    expect(autoDim.width).toBe(800);
    expect(autoDim.height).toBeLessThan(800);

    expect(wideDim.width).toBe(800);
    expect(wideDim.height).toBe(450);

    expect(squareDim.width).toBe(800);
    expect(squareDim.height).toBe(800);

    expect(tallDim.width).toBe(800);
    expect(tallDim.height).toBe(1422);
  });

  it("should render WebP and JPEG image formats", async () => {
    const table = parseMarkdownTable(`
| Metric | Value |
| --- | --- |
| Users | 100K |
    `);

    const webpBuffer = await renderTableToImage({
      table,
      format: "webp",
      customWidth: 400,
    });
    expect(webpBuffer.length).toBeGreaterThan(0);
    // WebP magic header starts with RIFF....WEBP
    expect(webpBuffer.toString("ascii", 0, 4)).toBe("RIFF");
    expect(webpBuffer.toString("ascii", 8, 12)).toBe("WEBP");

    const jpegBuffer = await renderTableToImage({
      table,
      format: "jpeg",
      customWidth: 400,
    });
    expect(jpegBuffer.length).toBeGreaterThan(0);
    // JPEG magic bytes: 0xFF 0xD8 0xFF
    expect(jpegBuffer[0]).toBe(0xff);
    expect(jpegBuffer[1]).toBe(0xd8);
    expect(jpegBuffer[2]).toBe(0xff);
  });

  it("should save rendered image to outputPath when specified", async () => {
    const table = parseMarkdownTable(`
| Tool | Status |
| --- | --- |
| Vitest | Active |
    `);

    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "mcp-test-"));
    const tmpFile = path.join(tmpDir, "subfolder", "table.png");

    try {
      const buffer = await renderTableToImage({
        table,
        outputPath: tmpFile,
      });

      expect(fs.existsSync(tmpFile)).toBe(true);
      const fileData = fs.readFileSync(tmpFile);
      expect(fileData).toEqual(buffer);
    } finally {
      fs.rmSync(tmpDir, { recursive: true, force: true });
    }
  });

  it("should render rich inline markdown, status badges, and zebra rows", async () => {
    const table = parseMarkdownTable(`
| Service | Package | Status | Notes |
| :--- | :--- | :---: | :--- |
| **Gateway** | \`fastmcp\` | Active | High throughput [docs](https://example.com) |
| *Worker* | \`takumi-js\` | In Progress | ~~legacy~~ v2 engine |
| Cache | \`lru\` | Done | In-memory store |
    `);

    const buffer = await renderTableToImage({
      table,
      title: "System Architecture",
      subtitle: "Production pipeline status",
      footer: "Confidential • Internal Only",
      theme: "editorial",
      zebraStriping: true,
      statusBadges: true,
    });

    expect(buffer).toBeDefined();
    expect(buffer.length).toBeGreaterThan(0);
  });
});
